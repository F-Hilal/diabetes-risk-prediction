import gradio as gr
import numpy as np
import joblib
from tensorflow.keras.models import load_model

# Model ve scaler'ı yükle
model = load_model("diabetes_model.keras")
scaler = joblib.load("scaler.pkl")

# Tahmin fonksiyonu
def predict_diabetes(pregnancies, glucose, blood_pressure, skin_thickness, insulin, bmi, dpf, age):
    # None değerleri 0'a çevir ve float tipine dönüştür
    inputs = [pregnancies, glucose, blood_pressure, skin_thickness, insulin, bmi, dpf, age]
    inputs = [float(x) if x is not None else 0.0 for x in inputs]

    input_data = np.array([inputs])
    input_scaled = scaler.transform(input_data)
    prediction = model.predict(input_scaled)[0][0]

    return f"⚠️ Yüksek Diyabet Riski (Tahmin: {prediction:.2f})" if prediction >= 0.5 \
           else f"✅ Düşük Diyabet Riski (Tahmin: {prediction:.2f})"

# Kullanıcı Dostu Gradio Arayüzü
